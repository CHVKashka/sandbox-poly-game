namespace SandboxPolyGame.Blocks;

/// <summary>
/// Тип логической ноды функционального блока (<see cref="LogicNode"/>). Ноды — это НЕ физические порты: физические
/// остаются только у механики и гидравлики (<see cref="ResourceType"/>: вал и труба, см. <see cref="ResourcePort"/>), а
/// электричество и логические значения идут через ноды и провода между ними (как в Stormworks — см.
/// Docs/05-world-and-vehicle-systems.md, «Ноды логики»).
/// </summary>
public enum NodeType
{
    /// <summary>Электричество — питание/потребление (батарея отдаёт, мотор/кнопка потребляют). Не физический ресурс:
    /// здесь нет ни кабеля-блока, ни ёмкости трубы — только связь между нодами.</summary>
    Electricity,

    /// <summary>Вкл/выкл (кнопка, переключатель, датчик). В рантайме хранится как 0/1 — см. <see cref="Runtime.NodeValue"/>.</summary>
    Boolean,

    /// <summary>Произвольное число (показание датчика, уставка).</summary>
    Number,
}
