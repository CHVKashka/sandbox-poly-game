namespace SandboxPolyGame.Blocks;

/// <summary>
/// Типы ресурсов, которыми обмениваются функциональные блоки через порты (см. <see cref="FunctionalBlockComponent"/>/
/// <see cref="ResourcePort"/>). Сама передача/сеть (трубы/кабели/валы, выравнивание давления, баланс мощности и
/// т.п. — см. Docs/05-world-and-vehicle-systems.md, «Ресурсы») пока не реализована — это только тип данных,
/// которым помечается порт/хранилище.
/// <para/>
/// Здесь ТОЛЬКО то, что физически течёт по трубе или передаётся валом. Электричество и логические значения (булево,
/// число) — НЕ физические ресурсы и здесь намеренно не живут (2026-10-04): у них свой тип — логические ноды
/// (<see cref="LogicNode"/>/<see cref="NodeType"/>), связи между которыми — провода логики, а не блоки-трубы.
/// </summary>
public enum ResourceType
{
    /// <summary>Несжимаемая жидкость (топливо, охлаждающая жидкость и т.п.) — хранится объёмом.</summary>
    Fluid,

    /// <summary>Механическая мощность на валу (момент при заданных оборотах).</summary>
    Torque,
}
